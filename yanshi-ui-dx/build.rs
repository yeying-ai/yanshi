//! Ensures `assets/app.generated.css` exists before `manganis::asset!` expands
//! during plain `cargo test` / `cargo clippy` on a fresh checkout where
//! `./yanshi-ui-dx/scripts/build.sh` (Tailwind CSS v4) has not run yet.

use std::fs;
use std::path::PathBuf;

fn main() {
  println!("cargo:rerun-if-changed=assets/app.generated.css");
  let Some(manifest_dir) = std::env::var_os("CARGO_MANIFEST_DIR") else {
    return;
  };
  let css_path = PathBuf::from(manifest_dir).join("assets/app.generated.css");
  if !css_path.exists() {
    if let Some(parent) = css_path.parent() {
      let _ = fs::create_dir_all(parent);
    }
    let _ = fs::write(
      &css_path,
      "/* Placeholder generated by build.rs; run ./yanshi-ui-dx/scripts/build.sh for Tailwind CSS v4 output. */\n",
    );
  }
}
